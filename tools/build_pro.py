#!/usr/bin/env python3
"""Build the Pro edition of the Order Flow Strategy indicator.

order-flow-strategy.pine (Standard) estimates order flow from lower-timeframe candles and
runs on every TradingView plan. The Pro edition swaps two marked blocks for TradingView's
real volume footprint (request.footprint), which TradingView only allows on Premium and
Ultimate plans: a script that calls it does not compile on lower plans, so the two
editions ship as separate files built from one source.

    python3 tools/build_pro.py

Edit order-flow-strategy.pine only, then run this script. Never edit the Pro file by hand.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "order-flow-strategy.pine"
OUT = ROOT / "order-flow-strategy-pro.pine"

SOURCE_BLOCK = """// @@FOOTPRINT_SOURCE_BEGIN
// Pro edition: real bid x ask volume footprint from TradingView (request.footprint, Premium or Ultimate plan).
// Bars without footprint data fall back to the lower-timeframe estimate.
int    fpTicksIn = input.int(0, "Footprint row size (ticks, 0 = auto)", minval = 0, group = G_OF, display = display.none, tooltip = "Price height of one footprint row, in ticks. Auto: NQ / MNQ 4, ES / MES 1, YM / MYM 5, other futures 2, BTC about $10, ETH about $1, other crypto 10, everything else 2.")
bool   needImb   = input.bool(true, "Flip candle must light up imbalances", group = G_OF, display = display.none, tooltip = "On the entry candle, buyers lifting the offer must print at least one buy imbalance (sellers hitting the bid: a sell imbalance for shorts), like the bold numbers on a bid x ask footprint.")

f_autoTicks() =>
    string r   = syminfo.root
    string tk  = syminfo.ticker
    bool   btc = str.contains(tk, "BTC") or str.contains(tk, "XBT")
    int    t   = syminfo.type == "futures" ? (r == "NQ" or r == "MNQ" ? 4 : r == "ES" or r == "MES" ? 1 : r == "YM" or r == "MYM" ? 5 : 2) : syminfo.type == "crypto" ? (btc ? int(math.round(10 / syminfo.mintick)) : str.contains(tk, "ETH") ? int(math.round(1 / syminfo.mintick)) : 10) : 2
    math.max(1, t)

int       fpTicks   = fpTicksIn > 0 ? fpTicksIn : f_autoTicks()
footprint ofp       = request.footprint(fpTicks, vaPct, imbRatio * 100)
bool      fpOk      = not na(ofp)
float     fpDelta   = fpOk ? ofp.delta() : na
float     fpVol     = fpOk ? ofp.total_volume() : na
float     fpPocMid  = na
bool      fpBuyImb  = false   // the candle has at least one buy imbalance
bool      fpSellImb = false   // the candle has at least one sell imbalance
if fpOk
    volume_row pocRow = ofp.poc()
    if not na(pocRow)
        fpPocMid := (pocRow.up_price() + pocRow.down_price()) / 2
    for fpRow in ofp.rows()
        if fpRow.has_buy_imbalance()
            fpBuyImb := true
        if fpRow.has_sell_imbalance()
            fpSellImb := true
// @@FOOTPRINT_SOURCE_END
"""

ROWS_HEAD = """        if fpOk
            realRows := true
            for fpRow in ofp.rows()
                float rowMid = (fpRow.up_price() + fpRow.down_price()) / 2
                int   rr     = math.max(0, math.min(n - 1, int(math.floor((rowMid - low) / stp))))
                array.set(buyR, rr, array.get(buyR, rr) + fpRow.buy_volume())
                array.set(sellR, rr, array.get(sellR, rr) + fpRow.sell_volume())
                if fpRow.has_buy_imbalance()
                    array.set(impB, rr, true)
                if fpRow.has_sell_imbalance()
                    array.set(impS, rr, true)
        else if cnt > 0
"""


def block(text, name):
    pat = re.compile(rf"^[ \t]*// @@{name}_BEGIN\n.*?^[ \t]*// @@{name}_END\n", re.S | re.M)
    m = pat.search(text)
    if not m:
        sys.exit(f"marker @@{name} not found in {SRC.name}")
    return m


def swap_once(text, old, new):
    if text.count(old) != 1:
        sys.exit(f"expected exactly one occurrence of: {old[:70]!r}")
    return text.replace(old, new)


def main():
    s = SRC.read_text()

    # 1) Order flow source: request.footprint() instead of the estimate hook
    m = block(s, "FOOTPRINT_SOURCE")
    s = s[: m.start()] + SOURCE_BLOCK + s[m.end():]

    # 2) Footprint cells: real rows first, estimate as fallback
    m = block(s, "FOOTPRINT_ROWS")
    rows = m.group(0)
    if "        if cnt > 0\n" not in rows:
        sys.exit("unexpected FOOTPRINT_ROWS block layout")
    rows = rows.replace("        if cnt > 0\n", ROWS_HEAD, 1)
    s = s[: m.start()] + rows + s[m.end():]

    # 3) Identity
    s = swap_once(s, 'indicator("Order Flow Strategy", shorttitle = "OFS",', 'indicator("Order Flow Strategy Pro", shorttitle = "OFS Pro",')
    s = swap_once(s, "//  ORDER FLOW STRATEGY (OFS)\n", "//  ORDER FLOW STRATEGY PRO (OFS Pro) · real volume footprint · TradingView Premium or Ultimate plan\n//  GENERATED by tools/build_pro.py from order-flow-strategy.pine: edit that file, not this one.\n")
    s = swap_once(
        s,
        """//   • Order flow is ESTIMATED from lower-timeframe candles (request.security_lower_tf): volume on up
//     candles counts as aggressive buying, volume on down candles as aggressive selling. TradingView
//     does not give scripts tick-level bid / ask data.
""",
        """//   • Order flow comes from TradingView's volume footprint (request.footprint): real buy and sell volume
//     per price row, the candle's point of control and diagonal bid x ask imbalances. Bars without
//     footprint data fall back to an estimate from lower-timeframe candles.
""",
    )
    s = swap_once(s, '"◆ ORDER FLOW STRATEGY", cCyan', '"◆ ORDER FLOW STRATEGY PRO", cCyan')

    OUT.write_text(s)
    print(f"built {OUT.relative_to(ROOT)} ({s.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
